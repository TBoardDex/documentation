// @ts-check
const lightCodeTheme = require('prism-react-renderer/themes/github');
const darkCodeTheme = require('prism-react-renderer/themes/dracula');

// EN -> ZH sidebar labels. Docusaurus 2.4.3 builds the sidebar from the
// English docs metadata only (`readCategoriesMetadata(version.contentPath)`),
// so without this map the Chinese site shows English category names.
// Regenerate with ../gen-sidebar-labels.py after renaming pages or categories.
const sidebarLabels = require('./src/sidebarLabels.json');

// TBoard-owned domains. Edit these constants when the sites move.
// NOTE: "url" is only used for canonical tags / sitemap / absolute links.
// The actual deployment target is decided by the GitHub Actions workflow
// and its Secrets (EN server and CN server), not by this file.
const EN_SITE_URL = 'https://docs.tboard.org';
const CN_SITE_URL = 'https://docs.tboard.cn';
const WWW_OVERSEAS = 'https://www.tboard.org';
const WWW_CHINA = 'https://www.tboard.cn';
const FORUM_URL = 'https://forum.tboard.org';
const ORG_URL = 'https://github.com/TBoardDex';

// Docusaurus appends " | <site title>" to every page title. The landing page
// therefore carries an empty doc title, so the browser tab shows the brand once
// instead of "TBoard Documentation | TBoard Documentation". Site title, tagline
// and navbar label are localised per build (docusaurus reloads this file for
// each locale, so the env var below is the locale being built right now).
const IS_ZH = process.env.DOCUSAURUS_CURRENT_LOCALE === 'zh';
const SITE_TITLE = IS_ZH ? 'TBoard 文档' : 'TBoard Documentation';
const SITE_TAGLINE = IS_ZH
  ? 'RK3588 / RK3588S 开源硬件与软件文档'
  : 'RK3588 / RK3588S open-source hardware and software documentation';

/** @type {import('@docusaurus/types').Config} */
const config = {
  title: SITE_TITLE,
  tagline: SITE_TAGLINE,
  favicon: 'img/favicon.svg',

  url: EN_SITE_URL,
  baseUrl: '/',
  organizationName: 'TBoardDex',
  projectName: 'documentation',
  onBrokenLinks: 'throw',
  onBrokenMarkdownLinks: 'warn',

  customFields: {
    cnSiteUrl: CN_SITE_URL,
    wwwOverseas: WWW_OVERSEAS,
    wwwChina: WWW_CHINA,
    forumUrl: FORUM_URL,
  },

  i18n: {
    defaultLocale: 'en',
    locales: ['en', 'zh'],
    localeConfigs: {
      en: { label: 'English', htmlLang: 'en' },
      zh: { label: '简体中文', htmlLang: 'zh-CN' },
    },
  },

  // Build-time local search index (no npm dependency, no workflow change).
  plugins: [require.resolve('./plugins/tboard-search.js')],

  presets: [
    [
      'classic',
      /** @type {import('@docusaurus/preset-classic').Options} */
      ({
        docs: {
          // Keep routeBasePath '/' so the EN build is served at the site root
          // and the ZH build is served from build/zh/ by the deploy workflow.
          routeBasePath: '/',
          sidebarPath: require.resolve('./sidebars.js'),
          // Localise the autogenerated sidebar for the Chinese build. The EN
          // build keeps the labels defined in docs/main/**/_category_.json.
          sidebarItemsGenerator: async ({ defaultSidebarItemsGenerator, ...args }) => {
            const items = await defaultSidebarItemsGenerator(args);
            if (process.env.DOCUSAURUS_CURRENT_LOCALE !== 'zh') {
              return items;
            }
            const localize = (list) =>
              (list || []).map((item) => {
                const label = sidebarLabels[item.label] || item.label;
                if (item.type === 'category') {
                  return { ...item, label, items: localize(item.items) };
                }
                if (item.type === 'link' || item.type === 'doc') {
                  return { ...item, label };
                }
                return item;
              });
            return localize(items);
          },
          editUrl: 'https://github.com/TBoardDex/documentation/tree/main/',
        },
        blog: false,
        theme: { customCss: require.resolve('./src/css/custom.css') },
      }),
    ],
  ],

  themeConfig:
    /** @type {import('@docusaurus/preset-classic').ThemeConfig} */
    ({
      image: 'img/og-cover.png',
      colorMode: { defaultMode: 'light', respectPrefersColorScheme: true },
      metadata: [
        { name: 'keywords', content: 'TBoard, RK3588, RK3588S, Rockchip, SBC, open source hardware, SDK' },
      ],
      navbar: {
        title: IS_ZH ? 'TBoard 文档' : 'TBoard Docs',
        logo: { alt: 'TBoard', src: 'img/tboard-logo.png' },
        items: [
          { type: 'custom-quicknav', position: 'left' },
          { type: 'custom-iconlink', position: 'left', label: 'Documentation', labelZh: '文档', icon: 'docs', to: '/' },
          { type: 'custom-iconlink', position: 'right', label: 'Forum', labelZh: '论坛', icon: 'forum', href: FORUM_URL },
          { type: 'custom-iconlink', position: 'right', label: 'Website', labelZh: '官网', icon: 'globe', href: WWW_OVERSEAS },
          { type: 'custom-iconlink', position: 'right', label: '中国站', labelZh: '中国站', icon: 'cn', href: WWW_CHINA },
          { type: 'custom-iconlink', position: 'right', label: 'GitHub', labelZh: 'GitHub', icon: 'github', href: ORG_URL },
          { type: 'localeDropdown', position: 'right' },
          // Do not declare a search item here: theme-classic mounts
          // @theme/SearchBar in the native top-right slot by itself.
        ],
      },
      footer: {
        style: 'dark',
        links: [
          {
            title: 'Documentation',
            items: [
              { label: 'Home', to: '/' },
              { label: 'Quick Start', to: '/quick-start' },
              { label: 'Downloads', to: '/downloads' },
              { label: 'TBoard R5A', to: '/tboard-r5a' },
            ],
          },
          {
            title: 'Sections',
            items: [
              { label: 'Accessories', to: '/accessories' },
              { label: 'Firmware Images', to: '/firmware-images' },
              { label: 'Others', to: '/others' },
              { label: 'Licenses', to: '/licenses/software' },
            ],
          },
          {
            title: 'TBoard',
            items: [
              { label: 'Website', href: WWW_OVERSEAS },
              { label: '中国站', href: WWW_CHINA },
              { label: 'Forum', href: FORUM_URL },
              { label: 'GitHub', href: ORG_URL },
            ],
          },
        ],
        copyright: 'Copyright © ' + new Date().getFullYear() + ' TBoard. All rights reserved.',
      },
      prism: { theme: lightCodeTheme, darkTheme: darkCodeTheme },
    }),
};

module.exports = config;
